#pragma once

#include <cstdint>
#include <string>

namespace OpenNPC {

/// Identifies the author of a ChatMessage.
enum class Role : std::uint8_t {
    System,     ///< Instruction or persona injected by the client application.
    User,       ///< Input coming from a human or from the client system.
    Assistant,  ///< Text generated by the language model.
    Tool        ///< Result returned by an external tool invocation.
};

/// A single message exchanged with a language-model provider.
struct ChatMessage {
    Role role{Role::User};  ///< Author of the message.
    std::string content;    ///< Raw text payload.
};

}  // namespace OpenNPC
